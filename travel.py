def match_source(host: str, snap: dict):
    """Allowed source entry for a host: host == domain or host ends with '.' + domain (never a bare suffix)."""
    host = (host or "").lower().rstrip(".")
    for s in snap["destination"]["sources"]:
        d = s["domain"].lower()
        if host == d or host.endswith("." + d):
            return s
    return None


def check_url(url: str, snap: dict):
    """(source entry, '') when the URL may be used, else (None, reason). https only, no userinfo, port 443."""
    try:
        parts = urllib.parse.urlsplit((url or "").strip())
        port = parts.port
    except ValueError:
        return None, "URL không hợp lệ"
    if parts.scheme != "https":
        return None, "chỉ nhận https"
    if parts.username is not None or parts.password is not None or "@" in parts.netloc:
        return None, "URL có thông tin đăng nhập (user@host)"
    if port not in (None, 443):
        return None, f"cổng {port} không được phép"
    host = parts.hostname
    if not host:
        return None, "URL không có tên miền"
    src = match_source(host, snap)
    if not src:
        return None, f"tên miền {host} không nằm trong danh sách nguồn cho phép"
    return src, ""


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *a, **k):
        return None


def _open(url: str, timeout: int = FETCH_TIMEOUT, accept_language: str = "en"):
    """One HTTP GET without following redirects. Returns a response-like object (.status, .headers, .read, .close).
    Replaced in tests; every check on the URL happens in fetch_source, not here."""
    from product_sources import UA

    opener = urllib.request.build_opener(_NoRedirect)
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "text/html,text/plain;q=0.9",
                                               "Accept-Language": accept_language})
    try:
        resp = opener.open(req, timeout=timeout)
    except urllib.error.HTTPError as e:   # 3xx (no redirect handler) and 4xx/5xx both arrive here
        resp = e
    if not hasattr(resp, "status"):
        resp.status = resp.getcode()
    return resp


class SourceError(RuntimeError):
    pass


def fetch_source(url: str, snap: dict, opener=None) -> dict:
    """Download one allowed page safely. Returns {"url": final url, "html": str, "source": entry}.
    Raises SourceError with the reason; the caller logs it and skips the page."""
    if opener is None:   # Accept-Language comes from the audience profile (B-1), not from code
        lang = snap["audience"].get("accept_language") or snap["script_lang"]
        opener = lambda u: _open(u, accept_language=lang)
    cur = url.strip()
    for hop in range(MAX_REDIRECTS + 1):
        src, why = check_url(cur, snap)
        if not src:
            raise SourceError(f"{cur}: {why}")
        if src.get("auto_fetch") is False:
            raise SourceError(f"{cur}: tên miền {src['domain']} không tải tự động được; mở trang bằng trình duyệt "
                              f"rồi dán vào cột facts_manual")
        resp = opener(cur)
        try:
            status = resp.status
            headers = {k.lower(): v for k, v in resp.headers.items()}
            if status in (301, 302, 303, 307, 308):
                loc = headers.get("location")
                if not loc:
                    raise SourceError(f"{cur}: chuyển hướng không có Location")
                cur = urllib.parse.urljoin(cur, loc)
                continue
            if status != 200:
                raise SourceError(f"{cur}: máy chủ trả mã {status}")
            ctype = headers.get("content-type", "").split(";")[0].strip().lower()
            if ctype not in ("text/html", "text/plain"):
                raise SourceError(f"{cur}: loại nội dung '{ctype or '?'}' không phải HTML/văn bản")
            clen = headers.get("content-length", "")
            if clen.isdigit() and int(clen) > MAX_PAGE_BYTES:
                raise SourceError(f"{cur}: trang quá lớn (> 2 MB)")
            raw = resp.read(MAX_PAGE_BYTES + 1)
            if len(raw) > MAX_PAGE_BYTES:
                raise SourceError(f"{cur}: trang quá lớn (> 2 MB)")
            m = re.search(r"charset=([\w-]+)", headers.get("content-type", ""), re.I)
            try:
                text = raw.decode(m.group(1) if m else "utf-8", "replace")
            except LookupError:
                text = raw.decode("utf-8", "replace")
            return {"url": cur, "html": text, "source": src, "plain": ctype == "text/plain"}
        finally:
            try:
                resp.close()
            except Exception:
                pass
    raise SourceError(f"{url}: quá {MAX_REDIRECTS} lần chuyển hướng")


class _TextParser(HTMLParser):
    SKIP = {"script", "style", "noscript", "template", "svg", "head"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts, self.skip = [], 0

    def handle_starttag(self, tag, attrs):
        if tag in self.SKIP:
            self.skip += 1
        self.parts.append(" ")

    def handle_endtag(self, tag):
        if tag in self.SKIP and self.skip:
            self.skip -= 1
        self.parts.append(" ")

    def handle_data(self, data):
        if not self.skip:
            self.parts.append(data)


def html_to_text(raw: str, plain: bool = False) -> str:
    """Page text: tags become spaces (a number split from its unit by <b> stays readable), entities decoded,
    whitespace collapsed."""
    if plain:
        text = raw
    else:
        p = _TextParser()
        p.feed(raw)
        p.close()
        text = "".join(p.parts)
    text = html.unescape(text).replace("\xa0", " ")
    return re.sub(r"\s+", " ", text).strip()


_QUOTES = str.maketrans({"‘": "'", "’": "'", "‚": "'", "‛": "'", "“": '"', "”": '"',
                         "„": '"', "–": "-", "—": "-", "‒": "-", "‑": "-", "‐": "-",
                         "−": "-", "\xa0": " "})


def match_form(text: str) -> str:
    """Form used to compare a quote with a page: quotes/dashes unified, case-insensitive, no whitespace at all
    (so "US$ 25" and "US$25" are the same)."""
    return re.sub(r"\s+", "", (text or "").translate(_QUOTES).casefold())


MIN_MANUAL_QUOTE_CHARS = 10   # facts_manual quotes are typed by hand (same floor as parse_facts_manual)


def quote_in_page(quote: str, page_text: str, min_chars: int = MIN_QUOTE_CHARS) -> bool:
    q = (quote or "").strip()
    if len(re.sub(r"\s+", " ", q)) < min_chars:
        return False
    return match_form(q) in match_form(page_text)


def select_text(text: str, question: str, budget: int) -> str:
    """At most `budget` characters of the page, keeping the passages that share most words with the question."""
    if len(text) <= budget:
        return text
    sentences = re.split(r"(?<=[.!?])\s+", text)
    chunks, cur = [], ""
    for s in sentences:
        if cur and len(cur) + len(s) > 600:
            chunks.append(cur)
            cur = s
        else:
            cur = f"{cur} {s}".strip()
    if cur:
        chunks.append(cur)
    words = {w for w in re.findall(r"\w{4,}", _plain(question))}
    scored = sorted(range(len(chunks)),
                    key=lambda i: (-len(words & set(re.findall(r"\w{4,}", _plain(chunks[i])))), i))
    keep, used = [], 0
    for i in scored:
        if used + len(chunks[i]) + 1 > budget:
            continue
        keep.append(i)
        used += len(chunks[i]) + 1
    return " ".join(chunks[i] for i in sorted(keep))



def _groq_json(prompt: str, max_tokens: int = 4000, temperature: float = 0.4) -> dict:
    """One Groq call returning parsed JSON (3 attempts). Tests replace this function."""
    from groq import Groq

    client = Groq(api_key=os.environ["GROQ_API_KEY"])
    model = os.environ.get("GROQ_MODEL", "qwen/qwen3.8-27b")
    last = None
    for attempt in range(3):
        try:
            r = client.chat.completions.create(model=model, messages=[{"role": "user", "content": prompt}],
                                               temperature=temperature, max_tokens=max_tokens)
            return demo._extract_json(r.choices[0].message.content or "")
        except Exception as e:
            last = e
            log(f"   Retry {attempt + 1}/2 after error: {str(e)[:120]}")
    raise RuntimeError(f"Groq failed: {last}")


