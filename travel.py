def _write_json(path: Path, data) -> None:
    """Atomic JSON write (T-19): temp file in the same folder, then replace."""
    path = Path(path)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(tmp, path)


def _read_json(path: Path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _strip_notes(obj):
    """Drop keys starting with '_' (profile notes) at every level."""
    if isinstance(obj, dict):
        return {k: _strip_notes(v) for k, v in obj.items() if not str(k).startswith("_")}
    if isinstance(obj, list):
        return [_strip_notes(v) for v in obj]
    return obj


def _plain(text: str) -> str:
    """Lower-case, no diacritics: for loose matching of place names and tags."""
    text = unicodedata.normalize("NFKD", (text or "").replace("đ", "d").replace("Đ", "D"))
    return "".join(c for c in text if not unicodedata.combining(c)).lower()


