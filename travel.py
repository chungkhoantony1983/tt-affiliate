def _cached_search(provider: str, query: str, fetch):
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    cache = CACHE_DIR / f"{provider}_{demo._slug(query, 80)}.json"
    if cache.exists() and time.time() - cache.stat().st_mtime < 24 * 3600:
        try:
            return json.loads(cache.read_text(encoding="utf-8"))
        except ValueError:
            pass   # half-written or damaged cache file = cache miss
    data = fetch()
    tmp = cache.with_name(cache.name + f".{os.getpid()}.tmp")
    tmp.write_text(json.dumps(data), encoding="utf-8")
    os.replace(tmp, cache)
    return data


MAX_JSON_BYTES = 2 * 1024 * 1024


def _get_json(url: str, headers: dict = None, timeout: int = 30):
    req = urllib.request.Request(url, headers={**MEDIA_UA, **(headers or {})})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        raw = r.read(MAX_JSON_BYTES + 1)
    if len(raw) > MAX_JSON_BYTES:
        raise RuntimeError("phản hồi tìm media quá lớn (> 2 MB)")
    return json.loads(raw)


def search_pixabay(query: str) -> list:
    key = os.environ.get("PIXABAY_API_KEY", "").strip()
    if not key:
        return []
    url = "https://pixabay.com/api/videos/?" + urllib.parse.urlencode(
        {"key": key, "q": query, "per_page": 50, "safesearch": "true"})
    hits = _cached_search("pixabay", query, lambda: _get_json(url).get("hits", []))
    out = []
    for h in hits:
        v = h.get("videos") or {}
        out.append({"provider": "pixabay", "id": str(h.get("id")), "type": "video", "page": h.get("pageURL", ""),
                    "author": h.get("user", ""), "license": PROVIDER_FIXED_LICENSE["pixabay"],
                    "tags": h.get("tags", ""), "duration": float(h.get("duration") or 0),
                    "variants": [{"url": x["url"], "w": x.get("width", 0), "h": x.get("height", 0)}
                                 for x in v.values() if isinstance(x, dict) and x.get("url")]})
    return out


def search_pexels(query: str) -> list:
    key = os.environ.get("PEXELS_API_KEY", "").strip()
    if not key:
        return []
    url = "https://api.pexels.com/videos/search?" + urllib.parse.urlencode(
        {"query": query, "per_page": 40, "orientation": "portrait"})
    hits = _cached_search("pexels", query, lambda: _get_json(url, {"Authorization": key}).get("videos", []))
    out = []
    for h in hits:
        slug = re.sub(r"[-/]", " ", urllib.parse.urlsplit(h.get("url", "")).path)
        out.append({"provider": "pexels", "id": str(h.get("id")), "type": "video", "page": h.get("url", ""),
                    "author": (h.get("user") or {}).get("name", ""), "license": PROVIDER_FIXED_LICENSE["pexels"],
                    "tags": slug, "duration": float(h.get("duration") or 0),
                    "variants": [{"url": f["link"], "w": f.get("width", 0), "h": f.get("height", 0)}
                                 for f in h.get("video_files", [])
                                 if f.get("link") and "mp4" in (f.get("file_type") or "")]})
    return out


def search_wikimedia(query: str) -> list:
    url = "https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode({
        "action": "query", "format": "json", "generator": "search", "gsrnamespace": 6,
        "gsrsearch": f"{query} filetype:bitmap", "gsrlimit": 20, "prop": "imageinfo",
        "iiprop": "url|extmetadata|mime|size", "iiurlwidth": 1920})
    pages = _cached_search("wikimedia", query, lambda: list(
        (_get_json(url).get("query") or {}).get("pages", {}).values()))
    out = []
    for p in pages:
        info = (p.get("imageinfo") or [{}])[0]
        meta = info.get("extmetadata") or {}
        mime = info.get("mime", "")
        if mime not in ("image/jpeg", "image/png", "image/webp") or not info.get("thumburl"):
            continue
        val = lambda k: re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", (meta.get(k) or {}).get("value", "")))).strip()
        out.append({"provider": "wikimedia", "id": str(p.get("pageid")), "type": "image",
                    "page": info.get("descriptionurl", ""), "author": val("Artist") or "unknown",
                    "license": val("LicenseShortName"), "mime": mime,
                    "tags": f"{p.get('title', '')} {val('Categories')} {val('ImageDescription')}",
                    "duration": 0.0,
                    "variants": [{"url": info["thumburl"], "w": info.get("thumbwidth", 0),
                                  "h": info.get("thumbheight", 0)}]})
    return out


def license_ok(license_name: str) -> bool:
    return any(re.search(p, (license_name or "").strip().lower()) for p in LICENSE_OK)


def media_problem(m: dict):
    """Why a media entry may not be used (C-0002-3, T-17), or None."""
    prov = m.get("provider")
    if prov not in PROVIDER_DOMAIN:
        return f"nhà cung cấp lạ '{prov}'"
    for k in ("page", "license", "id"):
        if not str(m.get(k) or "").strip():
            return f"thiếu '{k}'"
    if not license_ok(m["license"]):
        return f"giấy phép '{m['license']}' không nằm trong danh sách cho phép"
    parts = urllib.parse.urlsplit(m["page"])
    host = (parts.hostname or "").lower()
    d = PROVIDER_DOMAIN[prov]
    if parts.scheme != "https" or parts.username or not (host == d or host.endswith("." + d)):
        return f"trang {m['page'][:80]} không thuộc {d}"
    return None


def candidate_ok(c: dict, snap: dict) -> bool:
    tags = _plain(c.get("tags", ""))
    if any(a in tags for a in AI_TAGS) or re.search(r"(?<![a-z])ai(?![a-z])", tags.replace(",", " ")):
        return False   # D-8
    if media_problem(c):
        return False
    req = [_plain(t) for t in snap["destination"]["media_keywords"]["required_tags_any"]]
    if req and not any(re.search(rf"(?<![a-z0-9]){re.escape(r)}(?![a-z0-9])", tags) for r in req):
        return False   # R-4: footage must be tagged with the destination or a place in it
    return bool(c.get("variants"))


def pick_variant(c: dict) -> dict:
    """File whose short side is closest to 1080 (no 4K, T-9)."""
    return min(c["variants"], key=lambda v: abs(min(v.get("w") or 0, v.get("h") or 0) - 1080))


def _media_open(url: str, timeout: int = 60):
    """One GET without following redirects (response-like: .status, .headers, .read, .close)."""
    opener = urllib.request.build_opener(_NoRedirect)
    try:
        resp = opener.open(urllib.request.Request(url, headers=MEDIA_UA), timeout=timeout)
    except urllib.error.HTTPError as e:
        resp = e
    if not hasattr(resp, "status"):
        resp.status = resp.getcode()
    return resp


DOWNLOAD_DEADLINE = 180   # seconds for one media file, however slowly the server sends


def download_media(url: str, dest: Path, provider: str, opener=None) -> None:
    """Stream to dest.part then os.replace (T-9). https + provider CDN host at EVERY hop (redirects followed by hand,
    at most 3), Content-Type video/* or image/*, at most 80 MB, 180 s in total."""
    opener = opener or _media_open

    def host_ok(u):
        p = urllib.parse.urlsplit(u)
        h = (p.hostname or "").lower()
        return p.scheme == "https" and not p.username and (h == PROVIDER_CDN[provider]
                                                           or h.endswith("." + PROVIDER_CDN[provider]))
    part = dest.with_name(dest.name + ".part")
    deadline = time.time() + DOWNLOAD_DEADLINE
    cur = url
    try:
        for _ in range(MAX_REDIRECTS + 1):
            if not host_ok(cur):
                raise RuntimeError(f"địa chỉ tải {cur[:80]} không thuộc {PROVIDER_CDN[provider]} (https)")
            r = opener(cur)
            try:
                headers = {k.lower(): v for k, v in r.headers.items()}
                if r.status in (301, 302, 303, 307, 308):
                    cur = urllib.parse.urljoin(cur, headers.get("location", ""))
                    continue
                if r.status != 200:
                    raise RuntimeError(f"máy chủ trả mã {r.status}")
                ctype = headers.get("content-type", "").split(";")[0].strip().lower()
                if not (ctype.startswith("video/") or ctype.startswith("image/")):
                    raise RuntimeError(f"loại nội dung '{ctype or '?'}' không phải video/ảnh")
                clen = headers.get("content-length", "")
                if clen.isdigit() and int(clen) > MAX_MEDIA_BYTES:
                    raise RuntimeError(f"file quá lớn ({int(clen) // 1048576} MB)")
                total = 0
                with part.open("wb") as f:
                    while True:
                        if time.time() > deadline:
                            raise RuntimeError(f"tải quá {DOWNLOAD_DEADLINE} giây")
                        chunk = r.read(1 << 20)
                        if not chunk:
                            break
                        total += len(chunk)
                        if total > MAX_MEDIA_BYTES:
                            raise RuntimeError("file quá lớn (> 80 MB)")
                        f.write(chunk)
                os.replace(part, dest)
                return
            finally:
                try:
                    r.close()
                except Exception:
                    pass
        raise RuntimeError(f"quá {MAX_REDIRECTS} lần chuyển hướng")
    except Exception:
        part.unlink(missing_ok=True)
        raise


def _queries(seg: dict, question: str, snap: dict) -> list:
    mk = snap["destination"]["media_keywords"]
    visual = seg.get("visual") or ""
    hay = _plain(f"{question} {seg.get('line', '')}")
    qs = []
    for place, words in mk.get("places", {}).items():
        if re.search(rf"(?<![a-z0-9]){re.escape(_plain(place))}(?![a-z0-9])", hay):
            qs += [f"{words[0]} {visual}".strip(), words[0]]
    default = " ".join(mk["default"][:1])
    qs += [f"{default} {visual}".strip(), default]
    return list(dict.fromkeys(q for q in qs if q))


def build_media(script: dict, topic: dict, snap: dict, out_dir: Path, searchers: dict = None,
                downloader=None) -> None:
    """Pick one clip/image per scene (the outro reuses the hook's), download, fill script['media'] + segment['media']."""
    searchers = searchers or {"pixabay": search_pixabay, "pexels": search_pexels, "wikimedia": search_wikimedia}
    downloader = downloader or download_media
    segs, media, used = script["segments"], [], set()
    log(f"🖼️  Tìm clip/ảnh cho {len(segs)} cảnh...")
    for n, seg in enumerate(segs):
        if seg["kind"] == "outro":
            seg["media"] = segs[0]["media"]
            continue
        est = max(3.0, len(seg["line"].split()) / 2.6 + 0.6)
        chosen = None
        for provider in ("pixabay", "pexels", "wikimedia"):
            for q in _queries(seg, topic["question"], snap):
                try:
                    cands = searchers[provider](q)
                except Exception as e:
                    log(f"   ⚠️  {provider} '{q}': {str(e)[:100]}")
                    continue
                cands = [c for c in cands if (c["provider"], c["id"]) not in used and candidate_ok(c, snap)]
                cands.sort(key=lambda c: 0 if c["duration"] >= est else 1 if c["duration"] * 1.6 >= est else 2)
                for c in cands[:3]:
                    k = len(media)
                    var = pick_variant(c)
                    ext = ".mp4" if c["type"] == "video" else {"image/png": ".png", "image/webp": ".webp"}.get(c.get("mime"), ".jpg")
                    name = f"clip_{k}{ext}" if c["type"] == "video" else f"img_{k}{ext}"
                    try:
                        downloader(var["url"], out_dir / name, provider)
                    except Exception as e:
                        log(f"   ⚠️  {provider} {c['id']}: tải lỗi: {str(e)[:100]}")
                        continue
                    chosen = {"file": name, "provider": provider, "id": c["id"], "page": c["page"],
                              "author": c["author"], "license": c["license"], "type": c["type"]}
                    break
                if chosen:
                    break
            if chosen:
                break
        if not chosen:
            if not media:
                raise RuntimeError(f"Không tìm được clip/ảnh hợp lệ cho cảnh {n + 1} "
                                   f"(kiểm PIXABAY_API_KEY / từ khoá trong hồ sơ điểm đến)")
            log(f"   ⚠️  Cảnh {n + 1}: không có clip mới, dùng lại clip của cảnh trước")
            seg["media"] = segs[n - 1]["media"]
            continue
        used.add((chosen["provider"], chosen["id"]))
        media.append(chosen)
        seg["media"] = len(media) - 1
        log(f"   Cảnh {n + 1}: {chosen['provider']} {chosen['id']} ({chosen['license']})")
    script["media"] = media


def write_credits(out_dir: Path, script: dict) -> None:
    lines = ["Credits (media used in this video)", ""]
    for i, m in enumerate(script.get("media", [])):
        scenes = [str(n + 1) for n, s in enumerate(script["segments"]) if s.get("media") == i]
        lines.append(f"- {m['provider'].capitalize()} {m['type']} {m['id']} (scene {', '.join(scenes) or '-'}): "
                     f"{m['author']}, {m['license']} - {m['page']}")
    (out_dir / "credits.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")



