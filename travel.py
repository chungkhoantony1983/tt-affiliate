def tier_needed(claim: str, quote: str, category: str, snap: dict) -> int:
    """Worst tier accepted for this fact: 1 for visa / health / safety / law (by category or keyword), else the
    pillar's min_tier."""
    rules = snap["rules"]
    if category in rules["tier1_categories"]:
        return 1
    text = f"{claim} {quote}"
    for kw in rules["tier1_keywords"].get(snap["script_lang"], []):
        if re.search(rf"(?<!\w){re.escape(kw)}(?!\w)", text, re.I):
            return 1
    return snap["pillar"]["min_tier"]


def fact_tier_ok(fact: dict, snap: dict) -> bool:
    return int(fact.get("tier", 9)) <= tier_needed(fact.get("claim", ""), fact.get("quote", ""),
                                                   fact.get("category", "general"), snap)


