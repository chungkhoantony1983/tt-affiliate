MAX_HOOK_WORDS = 10         # on-screen question of the hook scene (Studio uses the same number)
MAX_SENTENCE_WORDS = 15     # spoken sentences of answer scenes


def write_script(topic: dict, facts: list, snap: dict, problems: list = None, previous: dict = None) -> dict:
    """Ask Groq for hook + answer segments + caption; the outro is built from the profile (C-0002-4)."""
    aud, pil = snap["audience"], snap["pillar"]
    sl, subs = snap["script_lang"], snap["subtitle_langs"]
    fact_lines = "\n".join(f"- {f['id']}: CLAIM: {f['claim']}\n  QUOTE: {f['quote']}" for f in facts)
    sub_rules = "\n".join(f"- subs.{l}: {aud['subtitle_tone'][l]}" for l in subs)
    seg = pil["answer_segments"]
    again = ""
    if problems:
        again = ("\nYour previous attempt had these problems, fix all of them:\n" + "\n".join(f"- {p}" for p in problems)
                 + "\nPrevious attempt:\n" + json.dumps(previous, ensure_ascii=False)[:5000] + "\n")
    prompt = f"""You write a short vertical video script that answers one traveller question using ONLY the facts below.

Question: {topic['question']}
Destination: {_dest_name(snap, sl)}
Topic: {pil['code']}
Operator notes: {topic.get('notes') or '-'}

FACTS (id, claim, exact quote):
{fact_lines}

Structure (JSON "segments"): first one "hook", then {seg['min']} to {seg['max']} "answer" segments. No outro (added by code).
- hook: "line" is the question above, word for word (do not change the place or any name in it); "fact_ids" is []. "text" is that question shortened to at most {MAX_HOOK_WORDS} words, using only words from the question.
- answer: each states ONE idea taken from the facts it cites; "fact_ids" lists the fact ids it uses (at least one).
- An answer may say ONLY what its cited facts say. No personal recommendation, opinion, praise, tip or remark about anything else, even if true ("worth a visit", "lovers will enjoy"...).
- "line": spoken, language code '{sl}', at most {MAX_LINE_CHARS} characters, 1 to 3 short sentences, EACH SENTENCE AT MOST {MAX_SENTENCE_WORDS} WORDS. Tone: {aud['tone']}
- Every number in line / text / subs / caption must appear in the QUOTE of a fact the segment cites, with the same meaning (money, days, percent...). Write numbers as digits, never as words. Do not add any fact, number, price, date or advice that is not in the facts.
- "text" of an answer: big on-screen words, at most {MAX_TEXT_WORDS} words, no sentence punctuation.
- "subs": object with one key per subtitle language {json.dumps(subs)}. Each value translates "line" faithfully and has EXACTLY the same number of sentences as "line" (sentences end with . ! or ?). {sub_rules}
- "visual": 2 to 4 English words describing stock footage that fits the idea (for example "street food market"). No people's names.
- "caption": one or two sentences for the post in the language with code '{snap['caption_lang']}', made ONLY of the question and the cited facts (no generalisation such as "many travelers", no extra advice). No hashtags, no emoji.

Return only JSON:
{{"caption": "...", "segments": [{{"kind": "hook", "line": "...", "text": "...", "subs": {{{', '.join(f'"{l}": "..."' for l in subs)}}}, "fact_ids": [], "visual": "..."}}, {{"kind": "answer", "line": "...", "text": "...", "subs": {{...}}, "fact_ids": ["f1"], "visual": "..."}}]}}
{again}"""
    raw = _groq_json(prompt, max_tokens=4000, temperature=0.5)
    return build_script(raw, topic, snap)


def hook_text(question: str, proposed: str) -> str:
    """On-screen hook = the traveller's question: whole (no "?") when it has at most MAX_HOOK_WORDS words; else the
    model's shortening, only if every word of it comes from the question (it must not swap the place); else the first
    MAX_HOOK_WORDS words followed by an ellipsis."""
    q = re.sub(r"\s+", " ", question).strip().rstrip("?!. ")
    words = q.split()
    if len(words) <= MAX_HOOK_WORDS:
        return q
    qset = {w.casefold() for w in re.findall(r"\w+", q)}
    prop = re.sub(r"\s+", " ", proposed or "").strip().rstrip("?!. ")
    pw = re.findall(r"\w+", prop)
    if pw and len(prop.split()) <= MAX_HOOK_WORDS and all(w.casefold() in qset for w in pw):
        return prop
    return " ".join(words[:MAX_HOOK_WORDS]) + "…"


def build_script(raw: dict, topic: dict, snap: dict) -> dict:
    """Normalise Groq's JSON into script.json (adds the outro, voice, hashtags)."""
    segs = []
    for s in raw.get("segments", []) if isinstance(raw, dict) else []:
        if not isinstance(s, dict) or s.get("kind") not in ("hook", "answer") or not str(s.get("line") or "").strip():
            continue
        if s["kind"] == "hook" and any(x["kind"] == "hook" for x in segs):
            continue
        sub = s.get("subs") if isinstance(s.get("subs"), dict) else {}
        seg = {
            "kind": s["kind"], "speaker": "narrator", "line": re.sub(r"\s+", " ", str(s["line"])).strip(),
            "subs": {l: re.sub(r"\s+", " ", str(sub.get(l) or "")).strip() for l in snap["subtitle_langs"]},
            "text": re.sub(r"\s+", " ", str(s.get("text") or "")).strip().rstrip(".!?"),
            "fact_ids": [str(i) for i in (s.get("fact_ids") or [])] if s["kind"] == "answer" else [],
            "visual": str(s.get("visual") or "").strip()[:60],
        }
        if seg["kind"] == "hook":
            q = topic.get("question") or seg["line"]
            seg["line"] = re.sub(r"\s+", " ", q).strip()   # the question itself, never reworded
            seg["text"] = hook_text(q, seg["text"])
        segs.append(seg)
    segs.append({**_outro(snap), "speaker": "narrator", "visual": ""})
    v = _voice(snap)
    return {
        "kind": "travel", "lang": snap["script_lang"], "destination": topic["destination"],
        "audience": topic["audience"], "pillar": topic["pillar"], "voice": v["voice"],
        "tts_provider": "edge", "hook": segs[0]["line"] if segs[0]["kind"] == "hook" else "",
        "caption": re.sub(r"\s+", " ", str(raw.get("caption") or "")).strip() if isinstance(raw, dict) else "",
        "hashtags": _hashtags(snap), "segments": segs, "media": [],
    }


def split_sentences(text: str) -> list:
    return [s for s in re.split(r"(?<=[.!?…])\s+", (text or "").strip()) if s]


def unsupported_chars(text: str, bold: bool = True) -> list:
    """Characters (emoji...) the on-screen font cannot draw."""
    odd = "".join(dict.fromkeys(c for c in (text or "") if ord(c) > 127))
    return _missing_glyphs(odd, bold) if odd else []


def _fc(msg: str) -> str:
    """One line of the exit-5 report, shown verbatim by Studio."""
    return "[FACT_CHECK] " + msg


def check_script(script: dict, facts: list, snap: dict, question: str, strict: bool = True) -> list:
    """All C-0002-1 / C-0002-4 problems, one `[FACT_CHECK] <Vietnamese sentence>` line each. strict=True also checks
    what Groq must deliver (segment count, sub sentence count, sentence length); Studio edits use strict=False."""
    errs = []
    aud = snap["audience"]
    by_id = {f["id"]: f for f in facts}
    segs = script.get("segments", [])
    sl, cl, subs = snap["script_lang"], snap["caption_lang"], snap["subtitle_langs"]
    if not segs or segs[0].get("kind") != "hook" or segs[-1].get("kind") != "outro":
        errs.append(_fc("Kịch bản phải bắt đầu bằng cảnh mở đầu (hook) và kết thúc bằng cảnh cuối (outro). "
                        "Tạo lại video từ Sheet."))
    answers = [s for s in segs if s.get("kind") == "answer"]
    seg = snap["pillar"]["answer_segments"]
    if strict and not seg["min"] <= len(answers) <= seg["max"]:
        errs.append(_fc(f"Cần {seg['min']}-{seg['max']} cảnh trả lời, hiện có {len(answers)}."))
    all_quotes = " ".join(f["quote"] for f in facts) + " " + question

    def number_problems(where: str, val: str, quotes: str):
        for shown in numbers_missing(val, quotes, aud):
            have = quote_numbers_shown(quotes, aud)
            src = f"nguồn chỉ ghi {', '.join(have[:5])}" if have else "nguồn không có số nào"
            errs.append(_fc(f"{where}: có số {shown} nhưng {src}. Sửa cho đúng số trong khung Dữ kiện rồi Dựng lại."))

    def word_problems(where: str, val: str, lang: str, own_question: bool = False):
        nw = number_words_in(val, snap, lang)
        if own_question:   # the hook IS the traveller's question: a spelled-out number it contains is theirs
            nw = [w for w in nw if not re.search(rf"(?<!\w){re.escape(w)}(?!\w)", question, re.I)]
        if nw:
            errs.append(_fc(f"{where}: số đang viết bằng chữ ('{nw[0]}'). Viết bằng chữ số để kiểm được, rồi Dựng lại."))

    def glyph_problems(where: str, val: str, bold: bool):
        bad = unsupported_chars(val, bold)
        if bad:
            errs.append(_fc(f"{where}: có chữ không hiển thị được (emoji hoặc ký hiệu lạ) {''.join(bad[:5])!r}. "
                            f"Xoá ký tự này rồi Dựng lại."))

    for n, s in enumerate(segs, 1):
        kind, line, text = s.get("kind"), (s.get("line") or "").strip(), (s.get("text") or "").strip()
        cảnh = f"Cảnh {n}"
        if kind not in ("hook", "answer", "outro"):
            errs.append(_fc(f"{cảnh}: loại cảnh '{kind}' không hợp lệ (chỉ hook, answer, outro). Tạo lại video từ Sheet."))
            continue
        if not line:
            errs.append(_fc(f"{cảnh}: lời đọc đang trống. Nhập lời đọc rồi Dựng lại."))
        if len(line) > MAX_LINE_CHARS:
            errs.append(_fc(f"{cảnh}: lời đọc dài {len(line)} ký tự, tối đa {MAX_LINE_CHARS}. Rút ngắn rồi Dựng lại."))
        limit = MAX_HOOK_WORDS if kind == "hook" else MAX_TEXT_WORDS
        if len(text.split()) > limit:
            errs.append(_fc(f"{cảnh}: chữ lớn dài quá {limit} từ. Rút ngắn rồi Dựng lại."))
        if re.search(r"\[[^\]]*\]", line):
            errs.append(_fc(f"{cảnh}: lời đọc có dấu [ ], bỏ phần trong ngoặc rồi Dựng lại."))
        if strict and kind == "answer":
            for sent in split_sentences(line):
                if len(sent.split()) > MAX_SENTENCE_WORDS:
                    errs.append(_fc(f"{cảnh}: có câu dài quá {MAX_SENTENCE_WORDS} từ ({sent[:40]!r}...). "
                                    f"Chia thành câu ngắn hơn."))
        sd = s.get("subs") or {}
        if kind in ("hook", "answer"):
            for l in subs:
                if not str(sd.get(l) or "").strip():
                    errs.append(_fc(f"{cảnh}: thiếu phụ đề {l.upper()}. Nhập phụ đề rồi Dựng lại."))
                elif strict and len(split_sentences(sd[l])) != len(split_sentences(line)):
                    errs.append(_fc(f"{cảnh}: phụ đề {l.upper()} phải có đúng {len(split_sentences(line))} câu như lời đọc."))
        if kind == "answer":
            ids = s.get("fact_ids") or []
            bad = [i for i in ids if i not in by_id]
            if not ids:
                errs.append(_fc(f"{cảnh}: cảnh trả lời chưa gắn dữ kiện nào. Chọn dữ kiện trong khung Dữ kiện."))
            if bad:
                errs.append(_fc(f"{cảnh}: dữ kiện {', '.join(bad)} không tồn tại."))
            for i in ids:
                if i in by_id and not fact_tier_ok(by_id[i], snap):
                    errs.append(_fc(f"{cảnh}: dữ kiện {i} lấy từ nguồn hạng {by_id[i]['tier']}, nhưng nội dung này "
                                    f"(visa, phí, y tế, an toàn, luật…) cần nguồn chính thức hạng 1. "
                                    f"Bỏ dữ kiện này hoặc thêm nguồn chính thức."))
            quotes = " ".join(by_id[i]["quote"] for i in ids if i in by_id)
        elif kind == "hook":
            quotes = all_quotes
        else:
            quotes = all_quotes + " " + " ".join(str(v) for v in sd.values())
        fields = [("Lời đọc", line, sl, True), ("Chữ lớn", text, sl, True)]
        fields += [(f"Phụ đề {l.upper()}", str(sd.get(l) or ""), l, False) for l in subs]
        for label, val, lang, bold in fields:
            where = f"{cảnh}, ô {label}"
            number_problems(where, val, quotes)
            if not (kind == "hook" and label.startswith("Phụ đề")):   # hook subs translate the traveller's question
                word_problems(where, val, lang, own_question=(kind == "hook"))
            glyph_problems(where, val, bold)
    for label, val, lang in (("Câu mở đầu", script.get("hook") or "", sl),
                             ("Chữ đăng kèm (caption)", script.get("caption") or "", cl)):
        number_problems(label, val, all_quotes)
        word_problems(label, val, lang, own_question=(label == "Câu mở đầu"))
        glyph_problems(label, val, True)
    return errs


def write_and_check(topic: dict, facts: list, snap: dict):
    """Groq writes, code checks; one retry with the problem list, then give up (returns (None, errors))."""
    script = write_script(topic, facts, snap)
    errs = check_script(script, facts, snap, topic["question"])
    if errs:
        log("   ⚠️  Kiểm tra lần 1 có lỗi, hỏi lại AI 1 lần:\n      " + "\n      ".join(errs))
        script = write_script(topic, facts, snap, errs, script)
        errs = check_script(script, facts, snap, topic["question"])
    return (None, errs) if errs else (script, [])



