_CUR = {"us$": "usd", "$": "usd", "usd": "usd", "dollar": "usd", "dollars": "usd", "vnd": "vnd", "₫": "vnd",
        "đ": "vnd", "dong": "vnd", "đồng": "vnd", "€": "eur", "£": "gbp", "%": "pct", "percent": "pct"}
_NUM_RE = re.compile(
    r"(?P<pre>US\$|USD|VND|\$|€|£|₫)?\s?(?P<num>\d{1,3}(?:[.,]\d{3})+(?:[.,]\d+)?|\d+(?:[.,]\d+)?)"
    r"(?P<suf>\s?(?:%|percent|USD|VND|dollars?|dong|đồng|đ|₫)(?!\w))?", re.I)


def _num_value(s: str) -> float:
    m = re.fullmatch(r"\d{1,3}(?:[.,]\d{3})+", s)
    if m:
        return float(re.sub(r"[.,]", "", s))
    m = re.fullmatch(r"(\d{1,3}(?:[.,]\d{3})+)[.,](\d+)", s)
    if m:
        return float(re.sub(r"[.,]", "", m.group(1)) + "." + m.group(2))
    return float(s.replace(",", "."))


def extract_numbers(text: str, aud: dict = None) -> list:
    """[(value, kind, shown)]. value: thousands separators dropped, 'million'-type words applied (audience profile
    `number_multipliers`). kind: currency / percent, else the unit class of the next word (audience profile
    `number_units`, e.g. day, night, person), else ''."""
    aud = aud or {}
    units = {w.casefold(): cls for cls, ws in (aud.get("number_units") or {}).items() for w in ws}
    mult = {w.casefold(): float(v) for w, v in (aud.get("number_multipliers") or {}).items()}
    text = re.sub(r"https?://\S+", " ", text or "")
    text = re.sub(r"#\w+", " ", text)
    out = []
    for m in _NUM_RE.finditer(text):
        value = _num_value(m.group("num"))
        kind = _CUR.get((m.group("pre") or m.group("suf") or "").strip().lower(), "")
        shown, pos = m.group(0).strip(), m.end()
        for _ in range(2):   # "1.5 million USD": multiplier word, then currency / unit word
            wm = re.match(r"\s?([^\W\d_]+)", text[pos:])
            if not wm:
                break
            w = wm.group(1).casefold()
            if w in mult:
                value *= mult[w]
            elif not kind and (w in units or w in _CUR):
                kind = units.get(w) or _CUR[w]
            else:
                break
            shown, pos = f"{shown} {wm.group(1)}", pos + wm.end()
        out.append((round(value, 6), kind, shown))
    return out


def numbers_missing(text: str, quote_text: str, aud: dict = None) -> list:
    """Numbers in `text` that do not occur in quote_text: same value, and the same class (currency, %, days...)
    when both sides state one. Limit: a number whose unit is not in the profile has class '' and matches any class."""
    have = [(v, k) for v, k, _ in extract_numbers(quote_text, aud)]
    bad = []
    for v, k, shown in extract_numbers(text, aud):
        if not any(v == hv and (not k or not hk or k == hk) for hv, hk in have):
            bad.append(shown)
    return bad


def quote_numbers_shown(quote_text: str, aud: dict = None) -> list:
    return list(dict.fromkeys(s for _, _, s in extract_numbers(quote_text, aud)))


def number_words_in(text: str, snap: dict, lang: str = None) -> list:
    """Spelled-out numbers ("twenty") of `lang` (default: the script language). The profile's `number_words` is a
    list (script language) or {lang: [...]}."""
    nw = snap["audience"].get("number_words") or []
    lang = lang or snap["script_lang"]
    words = nw.get(lang, []) if isinstance(nw, dict) else (nw if lang == snap["script_lang"] else [])
    mult = {k.casefold() for k in (snap["audience"].get("number_multipliers") or {})}
    found = []
    for w in words:
        for m in re.finditer(rf"(?<!\w){re.escape(w)}(?!\w)", text or "", re.I):
            # "1.5 million": a multiplier word right after a digit is part of a digit number, not a spelled-out one
            if w.casefold() in mult and re.search(r"\d[\d.,]*\s*$", text[:m.start()]):
                continue
            found.append(w)
            break
    return found


