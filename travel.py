def _default(env: str, key: str, cli) -> str:
    """CLI flag > environment variable > content/travel/defaults.json."""
    fallback = ""
    path = profile_dir() / "defaults.json"
    if path.is_file():
        try:
            data = _read_json(path)
        except ValueError as e:
            raise ProfileError(f"File {path} không phải JSON hợp lệ: {e}") from None
        if not isinstance(data, dict):
            raise ProfileError(f"File {path} phải là một đối tượng JSON, ví dụ {{\"destination\": \"...\"}}")
        fallback = str(data.get(key, ""))
    return (cli or os.environ.get(env) or fallback).strip()


def _csv_rows(path: str) -> list:
    with open(path, newline="", encoding="utf-8") as f:
        rows = [{k.strip(): (v or "") for k, v in r.items() if k} for r in csv.DictReader(f)]
    return [r for r in rows if r.get("question", "").strip() and not r.get("status", "").strip()]


def run_row(row: dict, args, base_dir: Path, tab: str) -> dict:
    question = row["question"].strip()
    pillar = row.get("pillar", "").strip()
    try:
        dest = row.get("destination", "").strip() or _default("TRAVEL_DESTINATION", "destination", args.destination)
        aud = row.get("audience", "").strip() or _default("TRAVEL_AUDIENCE", "audience", args.audience)
        snap = load_profiles(dest, aud, pillar)
    except ProfileError as e:
        log(f"❌ {question[:60]}: {e}")
        return {"status": "error", "error": str(e)}
    topic = {"kind": "travel", "question": question, "destination": dest, "audience": aud, "pillar": pillar,
             "source_urls": row.get("source_urls", "").strip(), "notes": row.get("notes", "").strip(),
             "facts_manual": row.get("facts_manual", "").strip(), "tab": tab,
             "created": datetime.now().isoformat(timespec="seconds"), "profile_snapshot": snap}
    name = (f"{datetime.now():%Y%m%d_%H%M%S}_travel_{demo._slug(dest, 16)}_{demo._slug(aud, 16)}_"
            f"{demo._slug(question)}")
    base_dir.mkdir(parents=True, exist_ok=True)
    for n in range(1, 100):   # never reuse a folder: _drop_if_no_video must only ever delete what this run made
        out_dir = base_dir / (name if n == 1 else f"{name}-{n}")
        try:
            out_dir.mkdir(exist_ok=False)
            break
        except FileExistsError:
            continue
    else:
        raise RuntimeError(f"Không tạo được thư mục mới cho video ({name})")
    log("\n" + "=" * 60)
    log(f"🧭 {question}  ({dest} / {aud} / {pillar})")
    log("=" * 60)
    _write_json(out_dir / "topic.json", topic)
    try:
        r = _run_row_body(topic, snap, out_dir, args)
    except Exception:
        _drop_if_no_video(out_dir)
        raise
    if r["status"] in ("needs_sources", "error"):
        _drop_if_no_video(out_dir)   # nothing worth keeping: no video, Studio would list an empty folder
        r.pop("dir", None)
    return r


def _drop_if_no_video(out_dir: Path) -> None:
    if not (out_dir / "video.mp4").exists():
        shutil.rmtree(out_dir, ignore_errors=True)


def _approve_now(topic: dict, out_dir: Path, args) -> dict:
    """--skip-approval / terminal 'y': approve at once. When approve refuses (5, 6, 7...) the row goes to `review`
    so the next run does not pick it up again (a hand-set status is still never overwritten)."""
    code = approve(out_dir, bool(args.keep_local))
    if code == 0:
        return {"status": "ready_for_manual_upload", "dir": str(out_dir)}
    _set_sheet_status(topic, "review")
    return {"status": "review", "dir": str(out_dir)}


def _run_row_body(topic: dict, snap: dict, out_dir: Path, args) -> dict:

    facts = research(topic, snap, out_dir)
    if not facts:
        log("❌ Không có dữ kiện hợp lệ nào (cần URL nguồn tải được hoặc cột facts_manual) → needs_sources")
        _set_sheet_status(topic, "needs_sources")
        return {"status": "needs_sources", "dir": str(out_dir)}
    _write_json(out_dir / "facts.json", facts)
    log(f"✅ {len(facts)} dữ kiện hợp lệ")

    script, errs = write_and_check(topic, facts, snap)
    if errs:
        log("❌ Kịch bản vẫn sai sau 2 lần → needs_sources:\n   " + "\n   ".join(errs))
        _set_sheet_status(topic, "needs_sources")
        return {"status": "needs_sources", "dir": str(out_dir), "error": "; ".join(errs[:3])}
    script["needs_render"] = True
    _write_json(out_dir / "script.json", script)
    build_media(script, topic, snap, out_dir)
    _write_json(out_dir / "script.json", script)
    voice_segments(script, snap, out_dir, list(range(len(script["segments"]))))
    _write_json(out_dir / "script.json", script)
    write_credits(out_dir, script)
    render(script, facts, snap, out_dir)
    script.pop("needs_render", None)
    _write_json(out_dir / "script.json", script)

    if args.skip_approval:
        return _approve_now(topic, out_dir, args)
    if demo.approval_mode() == "terminal":
        ans = input("\n✅ Approve? (y/n): ").strip().lower()
        if ans == "y":
            return _approve_now(topic, out_dir, args)
        return {"status": "rejected", "dir": str(out_dir)}
    _set_sheet_status(topic, "review")
    log(f"\n👀 Ready for review: open http://127.0.0.1:8000/studio and pick {out_dir.name}")
    return {"status": "review", "dir": str(out_dir)}


def main_new(args) -> int:
    """demo.py --travel ...: one video per run (the first pending row), or --refresh-facts DIR."""
    if getattr(args, "refresh_facts", None):
        try:
            r = refresh_facts(Path(args.refresh_facts), confirm=getattr(args, "confirm", None))
        except KeyError as e:
            log(f"❌ {OLD_FOLDER_MSG} (thiếu trường {e})")
            return 1
        except (OSError, ValueError) as e:
            log(f"❌ {e}")
            return 1
        log(f"\n{r['status']:<24} {r['dir']}")
        if r["status"] == "needs_sources":
            log("⚠️  KẾT QUẢ: needs_sources. Dữ kiện không còn khớp trang nguồn nên chưa làm mới được; thêm nguồn mới "
                "(cột source_urls / facts_manual) rồi tạo lại video.")
        return 1 if r["status"] == "error" else 0
    if getattr(args, "render_only", None) or getattr(args, "approve", None):
        return main_existing(args.render_only or args.approve, args)
    if not os.environ.get("GROQ_API_KEY"):
        log("❌ GROQ_API_KEY not set. Add it to .env (see .env.example)")
        return 1
    if os.environ.get("TRAVEL_TTS_PROVIDER", "edge").strip().lower() not in ("", "edge"):
        log("⚠️  P1 chỉ dùng edge-tts cho video du lịch; bỏ qua TRAVEL_TTS_PROVIDER")
    tab = args.tab if args.tab != "Tiktok" else os.environ.get("TRAVEL_TAB", "Travel")
    if args.sheet is not None:
        ref = args.sheet or os.environ.get("SPREADSHEET_ID", "")
        if not ref:
            log("❌ Truyền link Sheet hoặc đặt SPREADSHEET_ID trong .env")
            return 1
        from product_sources import TravelSheet

        rows = TravelSheet(ref, tab).pending()
    elif args.csv:
        rows = _csv_rows(args.csv)
    else:
        log("❌ Dùng --travel --sheet (tab Travel) hoặc --travel --csv FILE")
        return 1
    log(f"📄 {len(rows)} câu hỏi chưa làm (lần này làm câu đầu tiên)")
    if not rows:
        return 0
    try:
        r = run_row(rows[0], args, Path(args.output_dir), tab)
    except Exception as e:
        log(f"❌ {rows[0]['question'][:60]}: {e}")
        r = {"status": "error", "error": str(e)}
    log("\n" + "=" * 60 + "\n📊 SUMMARY\n" + "=" * 60)
    log(f"{r['status']:<24} {rows[0]['question'][:60]}  {r.get('dir', r.get('error', ''))}")
    return 1 if r["status"] == "error" else 0
