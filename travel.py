    for gender, v in edge.items():
        for key in ("voice", "rate", "pitch"):
            _need(errors, f"{wa} → voices.edge.{gender}", v, key, str)
    labels = aud.get("labels") if isinstance(aud.get("labels"), dict) else {}
    for key in ("info_as_of", "source", "follow", "photo_credit"):
        _need(errors, f"{wa} → labels", labels, key, str)
    if isinstance(aud.get("month_names"), list) and len(aud["month_names"]) != 12:
        errors.append(f"{wa}: 'month_names' cần đúng 12 tên tháng")

    sl, cl = aud.get("script_lang"), aud.get("caption_lang")
    langs = [l for l in [sl, cl] + list(aud.get("subtitle_langs") or []) if isinstance(l, str)]
