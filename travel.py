def apply_pronunciations(text: str, mapping: dict) -> str:
    """Whole-word, case-insensitive replacement, longer phrases first, in a single pass (a replacement is never
    re-replaced). Only used for the text sent to TTS (D-10)."""
    if not mapping:
        return text
    keys = sorted(mapping, key=len, reverse=True)
    lowered = {k.casefold(): v for k, v in mapping.items()}
    pat = re.compile("(?<!\\w)(?:" + "|".join(re.escape(k) for k in keys) + ")(?!\\w)", re.I)
    return pat.sub(lambda m: lowered.get(m.group(0).casefold(), m.group(0)), text)


def tts_text(line: str, snap: dict) -> str:
    text = re.sub(r"\[[^\]]*\]", "", line)
    text = apply_pronunciations(text, snap["destination"].get("pronunciations", {}).get(snap["script_lang"], {}))
    return re.sub(r"\s{2,}", " ", text).strip()


async def _edge_tts(text: str, voice: str, rate: str, pitch: str, output_path: str) -> None:
    import edge_tts

    # The free endpoint drops roughly 1 in 4 requests ("No audio was received"): retry with backoff.
    attempts = 6
    for attempt in range(attempts):
        try:
            await edge_tts.Communicate(text, voice, rate=rate, pitch=pitch).save(output_path)
            return
        except Exception as e:
            if attempt == attempts - 1:
                raise RuntimeError(await _explain_tts_failure(voice, e)) from None
            log(f"   Retry {attempt + 1}/{attempts - 1} after error: {str(e)[:80]}")
            await asyncio.sleep(2 * (attempt + 1))


async def _explain_tts_failure(voice: str, err: Exception) -> str:
    """Tell a wrong voice name (profile mistake) from a network / service problem (try again later)."""
    import edge_tts

    try:
        names = {v["ShortName"] for v in await edge_tts.list_voices()}
    except Exception:
        return (f"Không kết nối được dịch vụ đọc giọng edge-tts (lỗi mạng tạm thời, đã thử 6 lần): "
                f"{str(err)[:80]}. Kiểm tra mạng rồi Dựng lại.")
    if voice not in names:
        return f"Giọng '{voice}' không có trong edge-tts: sửa voices.edge trong hồ sơ đối tượng."
    return (f"edge-tts không trả âm thanh sau 6 lần thử (dịch vụ đang quá tải hoặc chặn tạm thời): "
            f"{str(err)[:80]}. Thử lại sau vài phút.")


def voice_segments(script: dict, snap: dict, out_dir: Path, indexes: list, tts=None) -> None:
    """(Re)make audio_N.mp3 for the given segments. All new files are made first and swapped in only when every one
    succeeded, so a failure leaves the old audio untouched (exit 3)."""
    from mutagen.mp3 import MP3

    tts = tts or _edge_tts
    v = _voice(snap)
    tmp = {i: out_dir / f"_new_audio_{i}.mp3" for i in indexes}
    try:
        for i in indexes:
            asyncio.run(tts(tts_text(script["segments"][i]["line"], snap), v["voice"], v["rate"], v["pitch"], str(tmp[i])))
            MP3(str(tmp[i]))   # unreadable file -> error
    except Exception as e:
        for p in tmp.values():
            p.unlink(missing_ok=True)
        raise RevoiceError(f"edge-tts failed, no audio changed: {str(e)[:200]}") from None
    for i, p in tmp.items():
        dest = out_dir / f"audio_{i}.mp3"
        os.replace(p, dest)
        seg = script["segments"][i]
        seg["duration"] = float(MP3(str(dest)).info.length)
        seg["audio_line"] = seg["line"]
    script["voice"] = v["voice"]
    script["tts_provider"] = "edge"


