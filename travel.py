def _stale_message(stale: list, d: Path, snap: dict) -> str:
    """The single `[FACTS_STALE] ...` line Studio shows (exit 6). `--confirm <ids>` appears only when some stale
    facts cannot be refreshed automatically."""
    def label(f):
        claim = " ".join((f.get("claim") or "").split())
        claim = claim[:40] + ("…" if len(claim) > 40 else "")
        return f"{f['id']} ({claim}; {_host(f)})" if claim else f"{f['id']} ({_host(f)})"
    auto = [f for f in stale if can_auto_refresh(f, snap) and not f.get("manual")]
    hand = [f for f in stale if f not in auto]
    oldest = min((f.get("checked_on") or "?") for f in stale)
    msg = (f"[FACTS_STALE] Dữ kiện {', '.join(label(f) for f in stale)} kiểm lần cuối {oldest}, đã quá {STALE_DAYS} "
           f"ngày (visa, phí, giá, luật có thể đã đổi). Làm mới miễn phí, mất khoảng 1 phút: chạy "
           f".venv/bin/python demo.py --travel --refresh-facts {shlex.quote(str(d))}.")
    if auto:
        msg += f" Tự làm mới được: {', '.join(f['id'] for f in auto)}."
    if hand:
        msg += (f" Không tự làm mới được (dán tay hoặc trang chặn tải): {', '.join(label(f) for f in hand)}; "
                f"hãy mở trang chính thức kiểm lại bằng mắt rồi chạy thêm --confirm "
                f"{','.join(f['id'] for f in hand)} sau lệnh trên.")
    return msg + " Dữ kiện nào có trang đã đổi sẽ bị bỏ, video có thể chuyển sang needs_sources."


