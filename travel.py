SUB_MAX_W = 840
SUB_Y, SUB_H = 1335, 215
EN_SIZE, SUB_SIZE, BIG_SIZE = 44, 32, 84
MAX_SLOWDOWN = 1.6
SUB_COLORS = ["#FFE9A0", "#BFE9FF", "#D8FFC2"]


def _split_balanced(words: list, k: int) -> list:
    k = max(1, min(k, len(words)))
    total = sum(len(w) + 1 for w in words)
    parts, cur, acc = [], [], 0
    for w in words:
        cur.append(w)
        acc += len(w) + 1
        if len(parts) < k - 1 and acc >= total * (len(parts) + 1) / k:
            parts.append(" ".join(cur))
            cur = []
    if cur:
        parts.append(" ".join(cur))
    return parts


def _parts_needed(text: str, font, draw) -> int:
    words = text.split()
    k = 1
    while k < len(words):
        if all(len(demo._wrap_px(draw, p, font, SUB_MAX_W)) <= 2 for p in _split_balanced(words, k)):
            return k
        k += 1
    return max(k, 1)


def subtitle_chunks(seg: dict, langs: list, fonts: dict, draw) -> list:
    """Cut one scene's text into pieces of at most 2 lines per language (T-18). Returns
    [{"main": str, "subs": {lang: str}, "weight": int}]; time is shared by `weight` (characters)."""
    line = seg["line"]
    subs = seg.get("subs") or {}
    sents = split_sentences(line)
    aligned = len(sents) > 1 and all(len(split_sentences(subs.get(l, ""))) == len(sents) for l in langs if subs.get(l))
    units = ([(sents[i], {l: split_sentences(subs.get(l, ""))[i] if subs.get(l) else "" for l in langs})
              for i in range(len(sents))] if aligned else [(line, {l: subs.get(l, "") for l in langs})])
    chunks = []
    for main, sd in units:
        k = max([_parts_needed(main, fonts["main"], draw)] +
                [_parts_needed(t, fonts["sub"], draw) for t in sd.values() if t])
        mp = _split_balanced(main.split(), k)
        sp = {l: _split_balanced(t.split(), k) if t else [] for l, t in sd.items()}
        for j in range(max(len(mp), *(len(v) for v in sp.values()), 1)):
            chunks.append({"main": mp[j] if j < len(mp) else "",
                           "subs": {l: (v[j] if j < len(v) else "") for l, v in sp.items()},
                           "weight": max(len(mp[j]) if j < len(mp) else 1, 1)})
    return chunks


def info_month_year(script: dict, facts: list, snap: dict) -> str:
    ids = {i for s in script["segments"] for i in s.get("fact_ids", [])}
    dates = sorted(f["checked_on"] for f in facts if f["id"] in ids and f.get("checked_on")) or [_today().isoformat()]
    d = date.fromisoformat(dates[0])
    return f"{snap['audience']['month_names'][d.month - 1]} {d.year}"


def source_names(script: dict, facts: list) -> list:
    ids = [i for s in script["segments"] for i in s.get("fact_ids", [])]
    by_id = {f["id"]: f for f in facts}
    return list(dict.fromkeys(by_id[i]["source_name"] for i in ids if i in by_id))


def _base_overlay(seg: dict, script: dict, facts: list, snap: dict, media: dict):
    """Full-frame RGBA: darkening at the top and bottom, big text, outro block, photo credit."""
    from PIL import Image, ImageDraw

    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    for y in range(0, 640):
        d.line([(0, y), (W, y)], fill=(0, 0, 0, int(165 * (1 - y / 640))))
    for y in range(1200, H):
        d.line([(0, y), (W, y)], fill=(0, 0, 0, int(185 * min((y - 1200) / 260, 1))))
    labels = snap["audience"]["labels"]
    if seg["text"]:
        demo._text_block(d, seg["text"], 230, demo._font(BIG_SIZE), max_w=W - 140, stroke=6, gap=18)
    if seg["kind"] == "outro":
        names = "; ".join(source_names(script, facts)) or "-"
        y = demo._text_block(d, labels["info_as_of"].format(month_year=info_month_year(script, facts, snap)), 820,
                             demo._font(52), stroke=5)
        demo._text_block(d, labels["source"].format(source=names), y + 24, demo._font(40, bold=False),
                         color="#EEEEEE", max_w=W - 200, stroke=4)
    if media and media["license"].lower().startswith("cc"):   # just above the subtitles: clear of the bottom ~350 px TikTok UI
        d.text((40, SUB_Y - 44), labels["photo_credit"].format(author=media["author"], license=media["license"]),
               font=demo._font(26, bold=False), fill="white", stroke_width=3, stroke_fill="black")
    return img


def _sub_overlay(chunk: dict, langs: list, fonts: dict):
    from PIL import Image, ImageDraw

    img = Image.new("RGBA", (W, SUB_H), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    y = 0
    if chunk["main"]:
        y = demo._text_block(d, chunk["main"], y, fonts["main"], max_w=SUB_MAX_W, stroke=4, gap=6)
    for n, l in enumerate(langs):
        if chunk["subs"].get(l):
            y = demo._text_block(d, chunk["subs"][l], y + 4, fonts["sub"], color=SUB_COLORS[n % len(SUB_COLORS)],
                                 max_w=SUB_MAX_W, stroke=3, gap=6)
    return img


SCENE_TIMEOUT, CONCAT_TIMEOUT = 600, 900   # seconds


def _ffmpeg(cmd: list) -> None:
    timeout = CONCAT_TIMEOUT if "concat" in cmd else SCENE_TIMEOUT   # the final join is the one with "-f concat"
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        raise RuntimeError(f"FFmpeg chạy quá {timeout} giây nên đã dừng. Kiểm tra clip nguồn rồi Dựng lại.") from None
    if result.returncode != 0:
        log(result.stderr[-3000:])
        raise RuntimeError(f"FFmpeg failed with exit code {result.returncode}")


def _render_scene(i, seg, m, script, facts, snap, out_dir, dur, speech, fonts, draw, dest, temp) -> tuple:
    """One scene -> silent mp4 of exactly `dur` seconds: media covering the frame (scaled to 1080 first),
    dark gradients, big text, subtitle pieces switched on and off by time. Returns (note, subtitle pieces)."""
    langs = snap["subtitle_langs"]
    path = out_dir / m["file"]
    inputs = []
    if m["type"] == "video":
        _, _, cdur = _clip_info(path)
        slow = 1.0 if cdur <= 0 or cdur >= dur else min(dur / cdur, MAX_SLOWDOWN)   # slower, never reversed
        pad = max(dur - (cdur * slow if cdur > 0 else 0), 0) + 0.1                  # then hold the last frame
        inputs += ["-threads", "2", "-i", str(path)]
        chain = (f"[0:v]scale={W}:{H}:force_original_aspect_ratio=increase,crop={W}:{H},setsar=1,"
                 f"setpts={slow:.4f}*PTS,fps={FPS},tpad=stop_mode=clone:stop_duration={pad:.3f},"
                 f"trim=duration={dur:.3f},setpts=PTS-STARTPTS,format=yuv420p[c]")
        note = path.name + (f" (x{slow:.2f} slower)" if slow > 1.01 else "")
    else:
        inputs += ["-i", str(path)]   # one frame in; zoompan makes all frames (a looped input would queue 14 MB frames)
        chain = (f"[0:v]scale=1620:2880:force_original_aspect_ratio=increase,crop=1620:2880,"
                 f"zoompan=z='min(1+0.0006*on,1.12)':d={int(dur * FPS) + 2}:x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':"
                 f"s={W}x{H}:fps={FPS},setsar=1,trim=duration={dur:.3f},setpts=PTS-STARTPTS,format=yuv420p[c]")
        note = path.name + " (still, zoom)"
    filters, k = [chain], 1
    base_png = out_dir / f"_scene_{i}.png"
    _base_overlay(seg, script, facts, snap, m).save(base_png)
    temp.append(base_png)
    inputs += ["-i", str(base_png)]   # single frame, overlay repeats it (no queue of RGBA frames)
    filters.append(f"[c][{k}:v]overlay=0:0:format=auto[o0]")
    k += 1
    cur = "o0"
    chunks = subtitle_chunks(seg, langs, fonts, draw)
    total_w = sum(c["weight"] for c in chunks)
    acc = 0
    for j, c in enumerate(chunks):
        t0 = speech * acc / total_w
        acc += c["weight"]
        t1 = dur if j == len(chunks) - 1 else speech * acc / total_w
        png = out_dir / f"_scene_{i}_sub{j}.png"
        _sub_overlay(c, langs, fonts).save(png)
        temp.append(png)
        inputs += ["-i", str(png)]
        nxt = f"o{j + 1}"
        filters.append(f"[{cur}][{k}:v]overlay=0:{SUB_Y}:enable='between(t,{t0:.3f},{t1:.3f})':format=auto[{nxt}]")
        cur = nxt
        k += 1
    filters.append(f"[{cur}]format=yuv420p,fps={FPS}[v]")
    # Few threads on purpose: x264 on a many-core machine keeps one 1080x1920 frame per thread in flight (~1 GB)
    _ffmpeg([demo._ffmpeg_bin(), "-y", "-v", "error", "-filter_threads", "2", "-filter_complex_threads", "2",
             *inputs, "-filter_complex", ";".join(filters), "-map", "[v]", "-t", f"{dur:.3f}", "-an",
             "-c:v", "libx264", "-threads", "2", "-x264-params", "rc-lookahead=8:bframes=2:ref=2", "-preset", "fast",
             "-crf", "21",
             "-pix_fmt", "yuv420p", str(dest)])
    return note, len(chunks)


def render(script: dict, facts: list, snap: dict, out_dir: Path) -> str:
    from PIL import Image, ImageDraw

    segs, media = script["segments"], script["media"]
    n = len(segs)
    for m in media:
        why = media_problem(m)
        if why:
            raise ValueError(f"Media {m.get('file')} không được dùng (C-0002-3): {why}")
        if Path(str(m.get("file", ""))).name != m.get("file") or not m.get("file"):
            raise ValueError(f"Tên file media '{m.get('file')}' không hợp lệ (phải nằm ngay trong thư mục video)")
        if not (out_dir / m["file"]).is_file():
            raise ValueError(f"Thiếu file media {m['file']}")
    langs = snap["subtitle_langs"]
    fonts = {"main": demo._font(EN_SIZE), "sub": demo._font(SUB_SIZE, bold=False)}
    draw = ImageDraw.Draw(Image.new("L", (10, 10)))
    plan, temp, scene_files = [], [], []
    log(f"🎬 Rendering travel video ({n} scenes, {len(media)} media), one scene at a time...")
    try:
        for i, seg in enumerate(segs):
            audio = out_dir / f"audio_{i}.mp3"
            if not audio.is_file():
                raise ValueError(f"Thiếu {audio.name}: dựng lại để đọc câu này")
            s0, s1 = _speech_bounds(audio, seg["duration"])
            dur = (s1 - s0) + demo.GAP + (demo.END_HOLD if i == n - 1 else 0)
            seg["scene_dur"], seg["speech_trim"] = round(dur, 3), [round(s0, 3), round(s1, 3)]
            plan.append((s0, s1))
            m = media[seg["media"]]
            scene_mp4 = out_dir / f"_scene_{i}.mp4"
            temp.append(scene_mp4)
            note, pieces = _render_scene(i, seg, m, script, facts, snap, out_dir, dur, s1 - s0, fonts, draw, scene_mp4, temp)
            scene_files.append(scene_mp4)
            log(f"   Scene {i + 1} [{seg['kind']}]: {dur:.1f}s  {note}  ({pieces} subtitle piece(s))")
        # Join: video copied scene after scene (hard cuts, nothing buffered); audio joined in one filter so it has no gaps
        listing = out_dir / "_scenes.txt"
        listing.write_text("".join(f"file '{p.name}'\n" for p in scene_files), encoding="utf-8")
        temp.append(listing)
        inputs = ["-f", "concat", "-safe", "0", "-i", str(listing)]
        filters = []
        for i, seg in enumerate(segs):
            inputs += ["-i", str(out_dir / f"audio_{i}.mp3")]
            s0, s1 = plan[i]
            fade_out_at = max(s1 - s0 - 0.05, 0)
            filters.append(f"[{i + 1}:a]atrim=start={s0:.3f}:end={s1:.3f},asetpts=PTS-STARTPTS,aresample=44100,"
                           f"aformat=channel_layouts=mono,afade=t=in:st=0:d=0.02,afade=t=out:st={fade_out_at:.3f}:d=0.05,"
                           f"apad=whole_dur={seg['scene_dur']:.3f}[a{i}]")
        filters.append("".join(f"[a{i}]" for i in range(n)) + f"concat=n={n}:v=0:a=1[aout]")
        tmp_video = out_dir / "_video.tmp.mp4"
        temp.append(tmp_video)
        cmd = [demo._ffmpeg_bin(), "-y", "-v", "error", *inputs, "-filter_complex", ";".join(filters), "-map", "0:v",
               "-map", "[aout]", "-c:v", "copy", "-c:a", "aac", "-b:a", "160k", "-movflags", "+faststart",
               str(tmp_video)]
        _ffmpeg(cmd)
        video = out_dir / "video.mp4"
        os.replace(tmp_video, video)
    finally:
        for p in temp:
            p.unlink(missing_ok=True)
    log(f"✅ Video: {video}  ({video.stat().st_size / 1e6:.1f} MB, {sum(s['scene_dur'] for s in segs):.1f}s)")
    return str(video)



