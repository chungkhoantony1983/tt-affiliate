def _set_sheet_status(topic: dict, status: str, only_from=("", "review")) -> None:
    """Update the row of this video in the Travel tab (T-7). Quiet no-op when no sheet is set up. A status the
    operator typed by hand (skip, done...) is never overwritten: only rows whose status is in `only_from` change."""
    sheet_ref = os.environ.get("SPREADSHEET_ID", "")
    if not (sheet_ref and status and Path("google-credentials.json").exists()):
        return
    try:
        from product_sources import TravelSheet

        sheet = TravelSheet(sheet_ref, topic.get("tab") or "Travel")
        row = sheet.find(topic["question"], topic["destination"], topic["audience"])
        if not row:
            return
        cur = row["status"].strip()
        if cur == status:
            return
        if cur not in only_from:
            log(f"📄 Sheet: giữ nguyên status '{cur}' (bạn đã đặt tay), không ghi '{status}'")
            return
        sheet.update(row, {"status": status})
        log(f"📄 Sheet '{topic.get('tab') or 'Travel'}': status={status}")
    except Exception as e:
        log(f"   ⚠️  Không cập nhật được Sheet ({str(e)[:100]}) — tự ghi status={status}")


